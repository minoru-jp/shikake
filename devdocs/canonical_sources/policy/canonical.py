"""shikakeのモデル化判断を支える独立した基本方針の正本。"""

from shikumi_devdoc.norms.common import canonical_source, summary
from shikumi_devdoc.norms.document import title


@summary(
    "変換・制限付きPythonの基盤となる構造的な確かさ、推測の境界、保守的な判断と利用者の責務。"
)
@canonical_source(
    "{{project.name}}: モデル化基本方針",
    filename="MODELING_POLICY.md",
    merge_policy="all",
    heading="title",
)
class MODELING_POLICY:
    """{{project.name}}は、Pythonのソースコードから、**他言語への変換や制限されたPythonの定義に利用できる構造的なモデル**を提供する。

    本文書は、個々の構文やAPIの判定条件を定める仕様書ではない。何を確かな情報として扱い、何を推測せず、判断をどこまで利用側へ委ねるかという、仕様・実装・レビューに共通する価値判断を示す。"""

    class PURPOSE:
        """{{project.name}}が提供する価値は、Pythonを実行せずに、**コードに書かれた構造を検討できること**にある。

        利用側は、入力を別の言語へ移すか、特定の構文を許すか、どの種類の処理に対応するかを判断できる。{{project.name}}自身が変換方法を決めたり、Pythonの実行結果を再現したり、入力コードの正しさを保証したりするわけではない。

        したがって、モデルには利用側の判断の根拠となる構造的な事実を残し、変換先固有の意味や実行時の推測を混ぜない。"""

        title @= "目的と提供する価値"

    class CERTAINTY:
        """{{project.name}}がいう**安定性**は、実行結果が変わらないことではない。ソースコードにおける識別子の導入が、構文上どれほど明快で、余計な解釈なしに扱える書き方であるかを評価する。

        この評価は、Pythonの実行意味だけを見る場合よりも慎重であり得る。例えば、モジュール直下の `global X` はPythonでは束縛先を変更しない。しかし、そこで `X` を導入する記述に不要なスコープ宣言が伴うことは、構造を利用する側にとって無視すべきとは限らない。{{project.name}}は、そのような導入を `unstable` と評価する。

        単一かつ無条件の導入であっても、それだけで `stable` と認定するわけではない。一方、**`stable` は良いコードの認定ではなく、`unstable` は悪いコードという断定でもない**。一般的な作法、冗長さ、読みやすさを採点するために、評価を広げない。

        より慎重な判定を採用するのは、名前の導入、スコープ、構造的な解釈に直接関わり、ASTから客観的に確認できる記述上の性質に限る。"""

        title @= "記述の確かさとしての安定性"

    class NO_SPECULATION:
        """{{project.name}}は、**ASTに書かれていることと、実際に何が起こるかを区別する**。

        条件が必ず成立するように見えても、実行経路を評価して構文上の条件性を消さない。式の値、実行時の参照先、動的な属性や別名、メソッド解決順序を推測して、見つからない情報を補わない。

        コードに表れた構造、識別子に対する操作、静的に発見した参照先候補は、それぞれ異なる根拠を持つ。候補を発見できたことを、名前の導入や実行時の参照先が確定したことと同一視しない。個々の情報を十分に裏付けられなければ、不明なまま渡す。

        Pythonの構文が直接規定する暗黙の操作は、実行を推測した結果ではなく、構文から得られる事実として扱える。ただし、任意の関数呼び出しの副作用まで追いかける理由にはしない。"""

        title @= "推測しないという選択"

    class DEFINITE_ASSIGNMENT:
        """{{project.name}}は、識別子の導入・書き込み・削除についてASTから確認できる構文事実を示すが、**読み取り時点で必ず代入済みであるか（確定代入）を判定しない**。

        束縛の `introduction`・`may_rebind`・`may_delete` は、それぞれ構文上の性質であり、実行順序や制御フロー上の確定代入を表すものではない。一般的な確定代入解析を提供することは、{{project.name}}の責務に含めない。これは技術的に不可能だからではなく、詳細な意味・データフロー解析へ責務を広げないための設計上の選択である。

        入力コードの正しさはコードの作成者に委ねる。変換や制限付きPythonの利用側で確定代入の保証が必要な場合は、**利用側が定める構文の制限・変換条件に基づいて独自に検査する**。{{project.name}}はその判定のための汎用的な確定代入結果を提供しない。"""

        title @= "確定代入を判定しないという責務の境界"

    class CONSERVATISM:
        """曖昧なコードを救済するために解析を際限なく増やすより、**根拠を限定して慎重な結果を返す**ことを重視する。静的な候補を取りこぼす場合や、Pythonとしては実行できるコードを制約により拒否する場合もある。

        特に外部から宣言された構造のように、誤って値として扱うことが利用側の前提を壊す対象については、便利さよりも明示的な許可と確実な拒否を優先する。

        ただし、保守的という言葉は、収集できるAST事実の見落としや、スコープを取り違えた候補の捏造を正当化しない。また、構造上の理由のない『好ましくない書き方』を独自に判定する口実にもならない。**厳しくする根拠と、厳しくしない境界の両方を説明できること**を求める。"""

        title @= "保守性とその限界"

    class RESPONSIBILITY:
        """{{project.name}}は、利用側に代わって入力コードの採否を決定するものではない。Kind・Structure・Featureによる構造、束縛に関する性質、静的に確認できた関係候補などを分けて示し、**その情報をどう利用するかは変換器や制限付き言語の設計者へ委ねる**。

        実装においても、同じAST事実を別々の解析経路で食い違うように解釈しない。新しい例外処理や推論機構を足す前に、責務と解析範囲を問い直す。

        レビューでは、根拠のある事実を誤って表現した不具合と、意図的に扱わない動的な可能性を区別する。判定をより精巧にできることだけでは、解析範囲を拡張する十分な理由にならない。

        個々の判定値、例外、対象構文、APIの契約は、`BINDING`・`RELATIONS`・`EXTERNAL` の各仕様正本（`devdocs/canonical_sources/specification/`）などの独立した仕様書に定める。"""

        title @= "利用側との責任分担と設計判断"
